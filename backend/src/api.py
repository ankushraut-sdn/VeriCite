import os
import shutil
import logging
from typing import Optional
from pydantic import BaseModel, Field
from fastapi import FastAPI, UploadFile, File, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware

from backend.src import config
from backend.src.orchestrator import RAGOrchestrator
from backend.src.exceptions import RAGError

# Configure logger
logger = logging.getLogger(__name__)

# Initialize FastAPI App
app = FastAPI(
    title="VeriCite API",
    description="Production-ready REST API orchestrating document ingestion, indexing, and citation-aware query resolution.",
    version="1.0.0"
)

# Enable CORS for frontend integration
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # In production, specify actual frontend origin (e.g., http://localhost:5173)
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Initialize global orchestrator
orchestrator = RAGOrchestrator()

# Define local uploads directory
UPLOADS_DIR = "./data/uploads"
os.makedirs(UPLOADS_DIR, exist_ok=True)

# Pydantic schemas
class QueryRequest(BaseModel):
    query: str = Field(..., description="The question or search query.", min_length=3)
    top_k: Optional[int] = Field(5, description="Number of document chunks to retrieve.", ge=1, le=20)
    min_similarity: Optional[float] = Field(0.0, description="Minimum similarity threshold (0.0 to 1.0).", ge=0.0, le=1.0)

